"""
palette.py —— 内置浏览器的共享色板（与南七日程日历配色保持一致）
================================================================

【为什么单独放一个模块】
内置浏览器是从 ustc-assistant 的 ui/browser_view.py 移植过来的，原文件写的是
`from ui import theme`，直接依赖日历 UI 的整套主题模块。移植到南七日程之后，
浏览器不应该反向依赖日历界面代码（那样浏览器就没法单独打包/单独复用，日历改
主题也会顺手把浏览器改坏）。所以这里只把浏览器页面上真正用到的那几个颜色常量
抄出来，独立成模块；view.py 里用 `from . import palette as theme` 引进来，这样
原来那些 `theme.PRIMARY` 的写法一个字都不用改，可读性和 diff 都保持原样。

【色值来源】
取自南七日程的暖鼠尾草绿（warm sage-green）配色。要换主题时只改这个文件即可，
浏览器里的所有控件都会跟着变。
"""

